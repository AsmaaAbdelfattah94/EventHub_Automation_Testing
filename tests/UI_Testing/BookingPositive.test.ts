
import { test, expect } from '../../fixtures/uiFixtures';

import { BOOKING_REF_PATTERN } from '../../utils/bookingReference';

// Test scenarios
const scenarios = [
  {
    id: 'TC_UI_01',
    name: 'Successfully book one ticket',
    eventName: 'Dilli Diwali Mela',
    quantity: 1
  },
  {
    id: 'TC_UI_02',
    name: 'Successfully book ten tickets',
    eventName: 'Hollywood Monsoon Night',
    quantity: 10
  }
];

for (const scenario of scenarios) {

  test(`${scenario.id} - ${scenario.name}`,
    async ({ page, eventsPage, bookingPage, myBookingsPage, trackBooking }) => {

      // Test data
      const customerName = `Automation Test ${Date.now()}`;
      const customerEmail = process.env.TEST_EMAIL;
      const customerPhone = '01066666666';

      if (!customerEmail) {
        throw new Error('TEST_EMAIL is missing');
      }

      // Variables shared between test steps
      let bookingReference = '';
      let cardPrice = 0;
      let expectedTotal = 0;

      // STEP 1 - Select event and quantity
      await test.step('Select event and ticket quantity',
        async () => {

          await eventsPage.openEvents();

          // Expected unit price comes from the event card, independent
          // of the booking page whose calculation is under test.
          cardPrice = await eventsPage.getEventPrice(
            scenario.eventName
          );

          expect(cardPrice).toBeGreaterThan(0);

          await eventsPage.selectEvent(
            scenario.eventName
          );

          await bookingPage.selectTicketQuantity(
            scenario.quantity
          );
        }
      );

      // STEP 2 - Verify price calculation before booking
      await test.step('Verify booking price calculation',
        async () => {

          const summary =
            await bookingPage.getTicketSummary();

          expect(summary.quantity).toBe(
            scenario.quantity
          );

          expect(
            summary.ticketPrice,
            'Booking summary unit price should match the event card'
          ).toBe(cardPrice);

          expectedTotal =
            cardPrice * scenario.quantity;

          const displayedTotal =
            await bookingPage.getDisplayedTotal();

          expect(displayedTotal).toBeCloseTo(
            expectedTotal,
            2
          );
        }
      );

      // STEP 3 - Enter customer details and confirm
      await test.step('Create booking',
        async () => {

          await bookingPage.enterCustomerDetails(
            customerName,
            customerEmail,
            customerPhone
          );

          await bookingPage.confirmBooking();

          // Capture the reference generated by EventHub and track it
          // for cleanup before any further assertion.
          bookingReference =
            await bookingPage.getBookingReference();

          trackBooking(bookingReference);

          expect(bookingReference).toMatch(
            BOOKING_REF_PATTERN
          );
        }
      );

      // STEP 4 - Verify booking confirmation
      await test.step('Verify booking confirmation details',
        async () => {

          // Confirm final total is correct
          const confirmationTotal =
            await bookingPage.getDisplayedTotal();

          expect(confirmationTotal).toBeCloseTo(
            expectedTotal,
            2
          );

          // Verify customer name
          await expect(
            page.getByText(customerName, {
              exact: true
            })
          ).toBeVisible();

          // Verify the selected ticket quantity (exact match, so a
          // displayed "10" does not satisfy an expected "1")
          await expect(
            bookingPage.confirmationValue('Tickets')
          ).toHaveText(String(scenario.quantity));
        }
      );

      // STEP 5 - Verify booking in My Bookings
      await test.step('Verify booking in My Bookings',
        async () => {

          await bookingPage.openMyBookings();

          await myBookingsPage.verifyBookingExists(
            bookingReference,
            scenario.eventName
          );

          // Open details for the exact booking
          await myBookingsPage.openBookingDetails(
            bookingReference
          );

          // Verify customer data
          await expect(
            page.getByText(customerName, {
              exact: true
            })
          ).toBeVisible();

          await expect(
            page.getByText(customerEmail, {
              exact: true
            })
          ).toBeVisible();

          await expect(
            page.getByText(customerPhone, {
              exact: true
            })
          ).toBeVisible();
        }
      );

      // The booking is cancelled by the trackBooking fixture.
    }
  );
}
