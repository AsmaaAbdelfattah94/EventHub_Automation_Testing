
import { test, expect } from '@playwright/test';

import { EventsPage } from '../../pages/EventsPage';
import { BookingPage } from '../../pages/BookingPage';
import { MyBookingsPage } from '../../pages/MyBookingPage';
import { clearAllBookings } from '../../utils/bookingCleanup';


// Use a dedicated automation account: clears ALL bookings for that account.
test.afterEach(async ({ page }) => {
  await test.step('Clear all bookings after test', async () => {
    await clearAllBookings(page);
  });
});

// Test scenarios
const scenarios = [
  {
    id: 'TC_UI_01',
    name: 'Successfully book one ticket',
    eventName: 'Dilli Diwali Mela',
    quantity: 1
  },
  {
    id: 'TC_UI_02',
    name: 'Successfully book ten tickets',
    eventName: 'Hollywood Monsoon Night',
    quantity: 10
  }
];

for (const scenario of scenarios) {

  test(`${scenario.id} - ${scenario.name}`,
    async ({ page }) => {

      // Initialize Page Objects
      const eventsPage = new EventsPage(page);
      const bookingPage = new BookingPage(page);
      const myBookingsPage = new MyBookingsPage(page);

      // Test data
      const customerName = `Automation Test ${Date.now()}`;
      const customerEmail = process.env.TEST_EMAIL;
      const customerPhone = '01066666666';

      if (!customerEmail) {
        throw new Error('TEST_EMAIL is missing');
      }

      // Variables shared between test steps
      let bookingReference: string | undefined;
      let expectedTotal = 0;

      try {

        // STEP 1 - Select event and quantity
        await test.step('Select event and ticket quantity',
          async () => {

            await eventsPage.openEvents();

            await eventsPage.selectEvent(
              scenario.eventName
            );

            await bookingPage.selectTicketQuantity(
              scenario.quantity
            );
          }
        );

        // STEP 2 - Verify price calculation before booking
        await test.step('Verify booking price calculation',
          async () => {

            const summary =
              await bookingPage.getTicketSummary();

            expect(summary.quantity).toBe(
              scenario.quantity
            );

            expect(summary.ticketPrice).toBeGreaterThan(0);

            expectedTotal =
              summary.ticketPrice * scenario.quantity;

            const displayedTotal =
              await bookingPage.getDisplayedTotal();

            expect(displayedTotal).toBeCloseTo(
              expectedTotal,
              2
            );
          }
        );

        // STEP 3 - Enter customer details and confirm
        await test.step('Create booking',
          async () => {

            await bookingPage.enterCustomerDetails(
              customerName,
              customerEmail,
              customerPhone
            );

            await bookingPage.confirmBooking();

            // Capture reference generated by EventHub
            bookingReference =
              await bookingPage.getBookingReference();

            expect(bookingReference).toMatch(
              /^[A-Z]-[A-Z0-9]+$/
            );

            console.log(
              `${scenario.id}: Booking reference = ${bookingReference}`
            );
          }
        );

        // STEP 4 - Verify booking confirmation
        await test.step('Verify booking confirmation details',
          async () => {

            // Confirm final total is correct
            const confirmationTotal =
              await bookingPage.getDisplayedTotal();

            expect(confirmationTotal).toBeCloseTo(
              expectedTotal,
              2
            );

            // Verify customer name
            await expect(
              page.getByText(customerName, {
                exact: true
              })
            ).toBeVisible();

            // Verify the selected ticket quantity
            const ticketsRow = page.getByText('Tickets', {
              exact: true
            }).last().locator('..');

            await expect(ticketsRow).toContainText(
              String(scenario.quantity)
            );

            // Verify booking reference
            expect(bookingReference).toBeDefined();
          }
        );

        // STEP 5 - Verify booking in My Bookings
        await test.step('Verify booking in My Bookings',
          async () => {

            if (!bookingReference) {
              throw new Error('Booking reference is missing');
            }

            await bookingPage.openMyBookings();

            await myBookingsPage.verifyBookingExists(
              bookingReference,
              scenario.eventName
            );

            // Open details for the exact booking
            await myBookingsPage.openBookingDetails(
              bookingReference
            );

            // Verify customer data
            await expect(
              page.getByText(customerName, {
                exact: true
              })
            ).toBeVisible();

            await expect(
              page.getByText(customerEmail, {
                exact: true
              })
            ).toBeVisible();

            await expect(
              page.getByText(customerPhone, {
                exact: true
              })
            ).toBeVisible();

          }
        );

      } finally {

        // STEP 6 - Clean up booking
        if (bookingReference) {

          await test.step('Cancel booking and clean up',
            async () => {

              await myBookingsPage.openMyBookings();

              await myBookingsPage.cancelBooking(
                bookingReference!
              );

              console.log(
                `${scenario.id}: Booking ${bookingReference} cancelled`
              );
            }
          );
        }
      }
    }
  );
}
